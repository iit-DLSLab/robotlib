// =============================================================================
// Includes
// =============================================================================
#include "doglib/hyq/joint_state_sweeper.hpp"

// =============================================================================
// Using Declarations
// =============================================================================
using namespace dls::dog::HyQ;
using namespace dls::dog;

// =============================================================================
// Constructors
// =============================================================================
JointStateSweeper::JointStateSweeper(double pstep) : step(pstep)
{
	for(int i=0; i<current_state.rows(); i++) {
		current_state(i) = jointLimits[i].min;
	}
}

// =============================================================================
// Implementation
// =============================================================================
const JointState& JointStateSweeper::next()
{
	for(int i=0; i<current_state.rows(); i++) {
		current_state(i) += step;
		if(current_state(i) > jointLimits[i].max) {
			current_state(i) = jointLimits[i].max;
		}
	}
	return current_state;
}

const JointState& JointStateSweeper::current() const
{
	return current_state;
}
