using namespace dls::dog;

// =============================================================================
// Constructors
// =============================================================================
TestK::TestK(ForwardKinematicsBase& fwdkin, InverseKinematicsBase& invkin) :
	fk(fwdkin), ik(invkin)
{ }

// =============================================================================
// Implementation
// =============================================================================
void TestK::testFK_IK(const JointState& q, Result& res)
{
	res.q = q;
	res.feet[LF] = fk.getFootPosLF(q);
	res.feet[RF] = fk.getFootPosRF(q);
	res.feet[LH] = fk.getFootPosLH(q);
	res.feet[RH] = fk.getFootPosRH(q);

	ik.getJointPosition(res.feet, res.q_ik);

	dls::rbd::Utils::CwiseAlmostZeroOp<double> approx(1E-4);
	res.equal = ( (res.q-res.q_ik).transpose().unaryExpr(approx).sum() == 0.0 );

}
